const fs = require('fs');
const path = require('path');
const countries = require('world-countries');

const root = path.resolve(__dirname, '..');
const optionsSource = fs.readFileSync(path.join(root, 'constants/profileOptions.ts'), 'utf8');
const match = optionsSource.match(/NATIONALITY_OPTIONS = (\[[^;]+\])/);
if (!match) throw new Error('Could not read NATIONALITY_OPTIONS');

const nationalities = JSON.parse(match[1]);
const normalize = (value) => String(value || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');

const overrides = {
    bosnian: 'BA', cabo_verdean: 'CV', congolese_brazzaville: 'CG', congolese_kinshasa: 'CD',
    djiboutian: 'DJ', dominican: 'DO', ecuadorian: 'EC', icelandic: 'IS', kosovan: 'XK',
    kyrgyz: 'KG', luxembourgish: 'LU', madagascan: 'MG', maldivian: 'MV', monacan: 'MC',
    myanmar: 'MM', north_macedonian: 'MK', saint_kittian_nevisian: 'KN', san_marino: 'SM',
    saudi: 'SA', slovenian: 'SI', surinamese: 'SR', tajik: 'TJ', timorese: 'TL',
    trinidadian_tobagonian: 'TT', vanuatu: 'VU',
};

const candidates = new Map();
for (const country of countries) {
    for (const demonym of [country.demonyms?.eng?.m, country.demonyms?.eng?.f]) {
        const key = normalize(demonym);
        if (!key) continue;
        const current = candidates.get(key) || [];
        if (!current.some((item) => item.cca2 === country.cca2)) current.push(country);
        candidates.set(key, current);
    }
}

const mapping = {};
for (const nationality of nationalities) {
    const key = normalize(nationality);
    if (overrides[key]) {
        mapping[key] = overrides[key];
        continue;
    }
    const matches = candidates.get(key) || [];
    const preferred = matches.find((country) => country.independent && country.unMember)
        || matches.find((country) => country.independent)
        || matches[0];
    if (!preferred) throw new Error(`No ISO mapping for nationality: ${nationality}`);
    mapping[key] = preferred.cca2;
}

const countryMapping = {};
for (const country of countries) {
    const aliases = [
        country.name?.common,
        country.name?.official,
        ...(country.altSpellings || []),
    ];
    for (const alias of aliases) {
        const key = normalize(alias);
        if (key && !countryMapping[key]) countryMapping[key] = country.cca2;
    }
}

const rows = Object.entries(mapping)
    .map(([key, iso]) => `    ${JSON.stringify(key)}: ${JSON.stringify(iso)},`)
    .join('\n');
const countryRows = Object.entries(countryMapping)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([key, iso]) => `    ${JSON.stringify(key)}: ${JSON.stringify(iso)},`)
    .join('\n');
const output = `// Generated by scripts/generate-nationality-iso.cjs from world-countries.\n`
    + `// Keep nationality aliases in the generator; do not hand-edit this file.\n`
    + `export const NATIONALITY_TO_ISO = {\n${rows}\n} as const;\n\n`
    + `export const COUNTRY_TO_ISO = {\n${countryRows}\n} as const;\n`;

fs.writeFileSync(path.join(root, 'constants/nationalityIso.generated.ts'), output);

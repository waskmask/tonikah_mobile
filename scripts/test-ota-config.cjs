const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const app = JSON.parse(fs.readFileSync(path.join(root, 'app.json'), 'utf8')).expo;
const eas = JSON.parse(fs.readFileSync(path.join(root, 'eas.json'), 'utf8'));
assert.equal(app.updates.url, `https://u.expo.dev/${app.extra.eas.projectId}`);
assert.equal(app.updates.enabled, true);
assert.equal(app.updates.checkAutomatically, 'ON_LOAD');
assert.equal(app.updates.fallbackToCacheTimeout, 0);
assert.equal(app.updates.useEmbeddedUpdate, true);
assert.equal(app.runtimeVersion.policy, 'appVersion');
assert.equal(eas.build.production.channel, 'production');
assert.equal(eas.build.production.environment, 'production');
assert.equal(eas.build.production.env.EXPO_PUBLIC_APP_ENV, 'prod');
assert.equal(eas.build.preview.channel, 'preview');
assert.equal(eas.build.preview.env.EXPO_PUBLIC_APP_ENV, 'dev');
assert.notEqual(eas.build.production.channel, eas.build.preview.channel);
const resolved = require('../app.config')({ config: app });
assert.deepEqual(resolved.updates, app.updates);
assert.deepEqual(resolved.runtimeVersion, app.runtimeVersion);
console.log('OTA configuration checks passed (project, runtime, launch fallback, channel/API isolation).');

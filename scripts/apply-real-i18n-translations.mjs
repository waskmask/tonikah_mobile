const enCommon = readJson(path.join(localesDir, 'en', 'common.json'));
const enChat = readJson(path.join(localesDir, 'en', 'chat.json'));
const enLanguages = readJson(path.join(localesDir, 'en', 'languages.json'));

let totalChanges = 0;

for (const locale of targetLocales) {
  const localeDir = path.join(localesDir, locale);

  const commonPath = path.join(localeDir, 'common.json');
  const common = readJson(commonPath);
  let commonChanges = 0;
  for (const [key, value] of Object.entries(commonTranslations[locale] || {})) {
    if (setIfFallback(common, enCommon, key, value)) commonChanges += 1;
  }
  if (commonChanges > 0) writeJson(commonPath, common);

  const chatPath = path.join(localeDir, 'chat.json');
  const chat = readJson(chatPath);
  const chatMap = { ...(chatTranslations[locale] || {}), ...(chatBaseByLocale[locale] || {}), ...(chatTailTranslations[locale] || {}) };
  let chatChanges = 0;
  for (const [key, value] of Object.entries(chatMap)) {
    if (setIfFallback(chat, enChat, key, value)) chatChanges += 1;
  }
  if (chatChanges > 0) writeJson(chatPath, chat);

  const languagePath = path.join(localeDir, 'languages.json');
  const languages = readJson(languagePath);
  let languageChanges = 0;
  let displayNames = null;
  try {
    displayNames = new Intl.DisplayNames([locale], { type: 'language' });
  } catch {
    displayNames = null;
  }
  if (displayNames) {
    for (const [key, code] of Object.entries(languageCodes)) {
      const translated = displayNames.of(code);
      if (setIfFallback(languages, enLanguages, key, translated)) languageChanges += 1;
    }
    if (languageChanges > 0) writeJson(languagePath, languages);
  }

  totalChanges += commonChanges + chatChanges + languageChanges;
  console.log(`${locale}: common ${commonChanges}, chat ${chatChanges}, languages ${languageChanges}`);
}

console.log(`Real translation fallback pass complete. Changed ${totalChanges} values.`);
